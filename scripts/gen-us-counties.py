#!/usr/bin/env python3
"""Regenerate crates/propagation/data/us_counties.txt, the county list of the US Counties award.

SOURCE: US Census Bureau, "2010 FIPS Codes for Counties and County Equivalent Entities"
(national_county.txt): https://www2.census.gov/geo/docs/reference/codes/files/national_county.txt
A work of the US government, so PUBLIC DOMAIN (17 U.S.C. 105). The download is checked against
the SHA-256 below before it is read. The 2010 vintage is used on purpose: it still has
Connecticut's eight counties, which the award counts (later vintages replace them with planning
regions).

WHAT IT BECOMES: the award's 3,077 counties, one "ST,Name" line each, sorted -- the Census
list for the 50 states, by the award's own rules for what is a county:
  * the District of Columbia is no state, and is left out;
  * the independent cities of Virginia and Carson City, Nevada, are not counties (a contact
    from one counts for a bordering county, the operator's choice), and are left out;
  * Baltimore City and St. Louis City are counties of their own, and stay;
  * Alaska counts its four Judicial Districts, not its boroughs.
The name drops " County" / " Parish"; Baltimore and St. Louis keep " City".

Run:  python3 scripts/gen-us-counties.py [--cache DIR]      (stdlib only; deterministic)
"""
import hashlib
import os
import sys
import tempfile
import urllib.request

URL = 'https://www2.census.gov/geo/docs/reference/codes/files/national_county.txt'
SHA256 = 'e176f37ffa5f88cc4773a9c0025579f9233dbfb193d5d76cb0d2b04de353e009'
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, 'crates', 'propagation', 'data', 'us_counties.txt')
TOTAL = 3077
NOT_STATES = {'DC', 'AS', 'GU', 'MP', 'PR', 'UM', 'VI'}
ALASKA = ['First Judicial District', 'Second Judicial District', 'Third Judicial District',
          'Fourth Judicial District']

cache = sys.argv[sys.argv.index('--cache') + 1] if '--cache' in sys.argv else tempfile.gettempdir()
path = os.path.join(cache, 'census-2010-national_county.txt')
if not os.path.exists(path):
    urllib.request.urlretrieve(URL, path)
raw = open(path, 'rb').read()
got = hashlib.sha256(raw).hexdigest()
if got != SHA256:
    sys.exit(f'{path}: SHA-256 {got}, expected {SHA256} -- not the file this list was made from')

rows = []
for line in raw.decode('latin-1').splitlines():
    if not line.strip():
        continue
    state, _st_fips, _co_fips, name, cls = line.split(',')
    if state in NOT_STATES or state == 'AK':
        continue
    if cls == 'C7' and not (state, name) in {('MD', 'Baltimore city'), ('MO', 'St. Louis city')}:
        continue  # an independent city (Virginia's, Carson City)
    for suffix in (' County', ' Parish'):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
    if name.endswith(' city'):
        name = name[: -len(' city')] + ' City'
    rows.append((state, name))
rows += [('AK', d) for d in ALASKA]
rows.sort()
if len(rows) != TOTAL or len(set(rows)) != TOTAL:
    sys.exit(f'{len(rows)} counties ({len(set(rows))} distinct), expected {TOTAL}')

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# The US Counties award: 3,077 counties, "STATE,Name". Generated by\n'
            '# scripts/gen-us-counties.py from the US Census Bureau 2010 county list\n'
            '# (public domain); see NOTICE. Do not edit by hand.\n')
    for state, name in rows:
        f.write(f'{state},{name}\n')
print(f'{OUT}: {len(rows)} counties')
