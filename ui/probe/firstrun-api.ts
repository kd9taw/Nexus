;(window as any).__probeWritten = () => written

export async function setExperienceLevel(l: string): Promise<any> {
  written.push(l)
  settings.experienceLevel = l
  try {
    localStorage.setItem('probe.level', l)
  } catch {
    /* the probe reads it back only after a reload */
  }
  return snapshot
}
export async function markSetupWizardSeen(): Promise<any> {
  settings.setupWizardSeen = true
  try {
    localStorage.setItem('probe.seen', '1')
  } catch {
    /* as for probe.level */
  }
  return snapshot
}
