// A FRESH INSTALL: one radio, the settings fixture with no experience answer and the setup wizard not
// yet done (`setupWizardSeen: false`, what the backend says where there was no settings file), and no
// stored feature state (uiStateLoad answers nothing), so the app opens the first-run wizard on its
// About-you step. Done is kept in localStorage under `probe.seen`, as the settings file would keep it.
// The answer the wizard writes is kept in localStorage under `probe.level`, so a reload (the probe opens
// Settings that way) reads it back as a station would. Every other export of src/api.ts answers `[]`,
// generated by the probe. Nothing here is a radio: layout is what is measured.
import settingsFixture from '../src/components/__fixtures__/defaultSettings.json'

const level = (() => {
  try {
    return localStorage.getItem('probe.level')
  } catch {
    return null
  }
})()
const seen = (() => {
  try {
    return localStorage.getItem('probe.seen') === '1'
  } catch {
    return false
  }
})()
const settings: any = {
  ...settingsFixture,
  mycall: 'KD9TAW',
  mygrid: 'EN52',
  setupWizardSeen: seen,
  ...(level ? { experienceLevel: level } : {}),
}
