beforeEach(() => {
  for (const spy of Object.values(api.spies)) {
    spy.mockClear()
    spy.mockImplementation(() => Promise.resolve(null))
  }
  api.get('getRigModels').mockImplementation(() => Promise.resolve([]))
  api.get('getAllRigModels').mockImplementation(() => Promise.resolve([]))
  api.get('getSerialPortsDetailed').mockImplementation(() => Promise.resolve([]))
  api.get('getBandPlan').mockImplementation(() => Promise.resolve([]))
  api.get('getAudioDevices').mockImplementation(() => Promise.resolve({ input: [], output: [] }))
  api.get('getCredentialsStatus').mockImplementation(() => Promise.resolve([]))
  api.get('getConnectionLog').mockImplementation(() => Promise.resolve([]))
  api.get('detectRigs').mockImplementation(() => Promise.resolve([]))
  api.get('appVersion').mockImplementation(() => Promise.resolve('1.6.1'))
  api.get('getSettings').mockImplementation(() => Promise.resolve(settingsFixture()))
})
afterEach(() => {
  cleanup()
  vi.restoreAllMocks()
})


function clickSave() {
  const save = screen
    .getAllByRole('button', { name: 'Save' })
    .find((b) => (b as HTMLButtonElement).type === 'submit')!
  fireEvent.click(save)
}

describe('log my Station power with an amplifier inline', () => {
  it('sits beside Station power, off by default, and saves on', async () => {
    renderPanel()
    fireEvent.click(await screen.findByRole('tab', { name: 'Digital' }))
    const sw = await screen.findByRole('switch', { name: /can't read is inline: log my Station power/ })
    expect(sw.getAttribute('aria-checked')).toBe('false')
    expect(sw.closest('.settings-field')!.textContent).toMatch(/Logging only/)
    fireEvent.click(sw)
    expect(sw.getAttribute('aria-checked')).toBe('true')
    clickSave()
    await waitFor(() => expect(api.get('setSettings')).toHaveBeenCalled())
    const calls = api.get('setSettings').mock.calls
    expect((calls[calls.length - 1][0] as Record<string, unknown>).logStationPowerWithAmp).toBe(true)
  })
})
