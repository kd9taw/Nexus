// @vitest-environment jsdom
//
// "AN AMPLIFIER NEXUS CAN'T READ IS INLINE: LOG MY STATION POWER" (#534). Nexus logs the power the
// radio measures, which behind an amplifier it cannot read (an IC-PW2 behind an IC-7300) is only
// the drive. A per-radio switch, off by default, beside Station power on the Digital tab; it saves
// with the radio's other per-radio settings. LOGGING ONLY — the engine side (what TX_PWR a contact
// gets) is pinned in engine.rs, and nothing here touches RF power.
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import { render, screen, cleanup, fireEvent, waitFor } from '@testing-library/react'
import { SettingsPanel } from './SettingsPanel'
import type { FeaturesApi } from '../useFeatures'
import defaultSettings from './__fixtures__/defaultSettings.json'

// THE BUDGET (2026-10-09). The slowest case here, "is reachable on the Digital tab and saves as a percent", takes
// 0.40 s and 0.48 s on one core (two runs); a loaded full suite on this box has run cases up to 20 times slower than
// one core, past vitest's 5 s default. 15 s is the house budget; a test that hangs still fails, after 15 s.
vi.setConfig({ testTimeout: 15_000 })

const api = vi.hoisted(() => {
  const spies: Record<string, ReturnType<typeof vi.fn>> = {}
  const get = (name: string) => {
    if (!spies[name]) spies[name] = vi.fn(() => Promise.resolve(null))
    return spies[name]
  }
  return { spies, get }
})

vi.mock('../api', async (importOriginal) => {
  const actual = await importOriginal<Record<string, unknown>>()
  const mod: Record<string, unknown> = {}
  for (const name of Object.keys(actual)) {
    mod[name] = typeof actual[name] === 'function' ? api.get(name) : actual[name]
  }
  return mod
})
vi.mock('../toast', () => ({
  pushToast: vi.fn(),
  withErrorToast: vi.fn(async (fn: () => Promise<unknown>) => fn()),
}))

